//! Write a ready-to-build Rust crate for a recompiled ROM.
//!
//! ```text
//! <out>/
//!   Cargo.toml       one dependency: gase-recomp-runtime (and gase's chips)
//!   rom.bin          your ROM: graphics, sound and data are read from it
//!   src/main.rs      boots the game in a frontend
//!   src/recomp/      the generated code (mod.rs + part_NNN.rs)
//!   BUILD.md
//! ```
//!
//! The crate is a workspace of its own, so it can live anywhere, even
//! inside this repository.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use crate::analysis::Program;
use crate::codegen::{Options, generate};

/// Where the generated crate finds the runtime.
#[derive(Clone, Debug)]
pub enum RuntimeSource {
    Path(PathBuf),
    Git { url: String, rev: String },
}

impl RuntimeSource {
    /// The runtime next to this generator when run from a checkout,
    /// otherwise the project's Git repository.
    #[must_use]
    pub fn default_for_this_build() -> Self {
        let here = Path::new(env!("CARGO_MANIFEST_DIR")).join("../runtime");
        match here.canonicalize() {
            Ok(p) if p.join("Cargo.toml").exists() => Self::Path(p),
            _ => Self::Git {
                url: "https://github.com/bthuner/gase-recomp".into(),
                rev: "develop".into(),
            },
        }
    }

    fn toml(&self) -> String {
        match self {
            Self::Path(p) => format!("{{ path = {:?} }}", p.display().to_string()),
            Self::Git { url, rev } => format!("{{ git = {url:?}, branch = {rev:?} }}"),
        }
    }
}

/// A crate name from the game's title.
#[must_use]
pub fn identifier(title: &str) -> String {
    let mut out = String::new();
    for c in title.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(c.to_ascii_lowercase());
        } else if !out.ends_with('_') && !out.is_empty() {
            out.push('_');
        }
    }
    let out = out.trim_end_matches('_').to_string();
    if out.is_empty() || !out.starts_with(|c: char| c.is_ascii_alphabetic()) {
        format!("game_{out}")
    } else {
        out
    }
}

/// Write the crate; returns the number of generated source files.
pub fn write_project(
    program: &Program,
    out: &Path,
    desktop: bool,
    runtime: &RuntimeSource,
) -> io::Result<usize> {
    let id = identifier(program.rom.title());
    let title = program.rom.title();
    let gen_dir = out.join("src/recomp");
    if gen_dir.exists() {
        fs::remove_dir_all(&gen_dir)?;
    }
    fs::create_dir_all(&gen_dir)?;
    let files = generate(program, &Options::default());
    for (name, src) in &files {
        fs::write(gen_dir.join(name), src)?;
    }
    fs::write(out.join("rom.bin"), &program.rom.data)?;
    let default = if desktop { "[\"sdl\"]" } else { "[]" };
    fs::write(
        out.join("Cargo.toml"),
        format!(
            "# \"{title}\", recompiled by gase-recomp. Regenerate rather than edit.\n\
             [package]\nname = \"{id}\"\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\n\n\
             # A workspace of its own: the crate can live anywhere.\n[workspace]\n\n\
             [dependencies]\ngase-recomp-runtime = {}\n\n\
             [features]\ndefault = {default}\n# A desktop window (needs the SDL2 development package).\nsdl = [\"gase-recomp-runtime/sdl\"]\n\n\
             # Generated code is big: optimise dependencies, keep our own build fast.\n\
             [profile.dev]\nopt-level = 1\n\n[profile.dev.package.\"*\"]\nopt-level = 3\n\n\
             [profile.release]\ncodegen-units = 16\n",
            runtime.toml()
        ),
    )?;
    fs::create_dir_all(out.join("src"))?;
    fs::write(
        out.join("src/main.rs"),
        format!(
            "//! \"{title}\", statically recompiled by gase-recomp.\n//!\n\
             //! `src/recomp/` holds the game's 68000 code translated to Rust; the\n\
             //! runtime provides the rest of the console (gase's chips).\n\n\
             mod recomp;\n\n\
             /// The console the recompiled code runs on.\n\
             pub type Machine = gase_recomp_runtime::GenesisMachine;\n\n\
             fn main() {{\n    gase_recomp_runtime::main(&gase_recomp_runtime::GameInfo {{\n        \
             title: recomp::TITLE,\n        rom_crc32: recomp::ROM_CRC32,\n        rom_size: recomp::ROM_SIZE,\n        \
             code: recomp::code(),\n    }});\n}}\n"
        ),
    )?;
    fs::write(
        out.join("BUILD.md"),
        format!(
            "# {title}\n\nGenerated by **gase-recomp**.\n\n\
             ```sh\ncargo run --release                          # desktop window (if built with the `sdl` feature)\n\
             cargo run --release -- --headless --frames 600 --ppm shot.ppm\n```\n\n\
             `rom.bin` must be the ROM this code was recompiled from (its CRC32 is checked).\n\n\
             ## Code the analysis missed\n\n\
             When the game reaches code the static analysis did not find (a jump\n\
             table, code copied to RAM...), gase's 68000 interpreter runs it, so the\n\
             game keeps going, and the address is appended to `gase_missing.txt`.\n\
             Recompile with `gase-recomp recomp <rom> -o <here>`: the file is picked\n\
             up and those addresses become recompiled functions. This is the\n\
             *coverage feedback loop* described in the making-of.\n"
        ),
    )?;
    Ok(files.len())
}
